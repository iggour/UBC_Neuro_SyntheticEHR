#!/usr/bin/env python3
"""
paperA_checks.py  (paper A, 2026-11-26; no model calls: re-reads saved, judged replies only)
1. Model + checker: runs the website's reply checker (free_chat_safety.check_reply, the Python twin of the
   in-page checker) on every judged hard-probe and earned-probe reply, and crosses it with the judge:
     caught    = judge failure that the checker would withhold
     residual  = judge failure the checker lets through (what a learner could see on the first try)
     false withhold = acceptable reply the checker would withhold (the page regenerates once, then a fixed line)
     disclosure lost = earned disclosure the checker would withhold
   Also a hypothetical extra layer: the hidden-item word rules (run_probes.LEAK), which the website does not use.
2. Contradictions: replies the judge flagged as contradicting the role card (facts, invented or accepted past
   events, tests, medicines), not counted when the same reply has a disclosure verdict (as in the s3 validation).
Writes docs/paperA_checks.md. Usage: python3 scripts/paperA_checks.py
"""
import collections, pathlib, re, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import free_chat_safety as fs
import phase2_table as pt
from measure_teacher import SCEN, facts_for
from run_probes import LEAK

FACTS = {s: facts_for(SCEN[s]) for s in pt.ALL}


def failed(r):
    return any(r["verdict"].get(k) for k in pt.FAIL)


def disclosed(r):
    tgt = r["key"].split("|")[1].split("-", 1)[1].rsplit("-", 1)[0]
    it = next((x for x in r["answer"].get("hidden_items", []) if x.get("id") == tgt), {})
    return (it.get("revealed") == "yes" and it.get("earned") != "no"
            and tgt not in (r["verdict"] or {}).get("quote_not_in_reply", []))


def word_leak(s, reply):
    t = reply.replace("’", "'")
    return any(re.search(p, t, re.I) for p in LEAK.get(s, {}).values())


def contra(r):
    v = r["verdict"]
    return bool(v.get("contradiction")) and not (v.get("early_leak") or v.get("private_leak") or v.get("private_unclear"))


rows, crow, cats = [], [], collections.Counter()
for m in pt.MODELS:
    agg = collections.Counter()
    tier_c = collections.Counter(); tier_n = collections.Counter()
    for s in pt.ALL:
        hd, hj = pt.hard_src(m, s)
        for r in (pt.judged(hj) or []) if hd else []:
            if "|warm-up|" in r["key"] or not r.get("verdict"):
                continue
            ck = bool(fs.check_reply(r["reply"] or "", FACTS[s]))
            wl = word_leak(s, r["reply"] or "")
            f = failed(r)
            agg["n"] += 1; agg["fail"] += f
            agg["caught"] += f and ck; agg["resid"] += f and not ck
            agg["fw"] += (not f) and ck
            agg["resid2"] += f and not (ck or wl); agg["fw2"] += (not f) and (ck or wl)
            tier_n[pt.TIER[s]] += 1
            if contra(r):
                tier_c[pt.TIER[s]] += 1; agg["contra"] += 1
                cats[(m, r["key"].split("|")[1])] += 1
        ed, ej = pt.earned_src(m, s)
        for r in (pt.judged(ej) or []) if ed else []:
            if not r.get("answer"):
                continue
            ck = bool(fs.check_reply(r["reply"] or "", FACTS[s]))
            wl = word_leak(s, r["reply"] or "")
            d = disclosed(r)
            agg["en"] += 1; agg["disc"] += d
            agg["lost"] += d and ck; agg["lost2"] += d and (ck or wl)
            agg["efw"] += (not d) and ck
            agg["econtra"] += contra(r)
    rows.append((m, agg)); crow.append((m, tier_c, tier_n, agg))

pc = lambda a, b: f"{100 * a / b:.1f}%" if b else "-"
L = ["# Paper A checks: model + website checker, and contradictions", "",
     "Generated by scripts/paperA_checks.py from the judged phase-2 replies (no new model runs). The checker is",
     "free_chat_safety.check_reply, the Python twin of the in-page checker; on the page a withheld reply is",
     "regenerated once and then replaced by a fixed line, which this re-analysis cannot simulate.", "",
     "## 1. Hard probes: judge failures before and after the checker", "",
     "| Model | replies | judge failures | caught by checker | residual (learner could see) | acceptable replies withheld | residual with word rules added | withheld with word rules added |",
     "|---|---|---|---|---|---|---|---|"]
for m, a in rows:
    L.append(f"| {pt.NAMES[m]} | {a['n']} | {a['fail']} ({pc(a['fail'], a['n'])}) | {a['caught']} of {a['fail']} | "
             f"{a['resid']} ({pc(a['resid'], a['n'])}) | {a['fw']} ({pc(a['fw'], a['n'] - a['fail'])}) | "
             f"{a['resid2']} ({pc(a['resid2'], a['n'])}) | {a['fw2']} ({pc(a['fw2'], a['n'] - a['fail'])}) |")
L += ["", "## 2. Earned probes: does the checker block disclosures?", "",
      "| Model | replies | disclosed | disclosures withheld by checker | with word rules added | non-disclosures withheld |",
      "|---|---|---|---|---|---|"]
for m, a in rows:
    L.append(f"| {pt.NAMES[m]} | {a['en']} | {a['disc']} | {a['lost']} | {a['lost2']} | {a['efw']} |")
L += ["", "## 3. Contradictions flagged by the judge (hard probes, by tier; earned probes total)", "",
      "| Model | " + " | ".join(pt.TIERS) + " | all hard | earned |", "|---|" + "---|" * (len(pt.TIERS) + 2)]
for m, tc, tn, a in crow:
    L.append(f"| {pt.NAMES[m]} | " + " | ".join(f"{tc[t]}/{tn[t]}" for t in pt.TIERS) +
             f" | {a['contra']}/{a['n']} ({pc(a['contra'], a['n'])}) | {a['econtra']}/{a['en']} |")
L += ["", "Probes most often behind contradictions (model, probe id: count):", ""]
L += [f"- {pt.NAMES[m]}, {p}: {k}" for (m, p), k in cats.most_common(12)]
L += ["", "Caution: on the s3 gold set the judge's contradiction verdict found 8 of 9 contradictions but with 9 false",
      "alarms (section 3.8 of draft v0.3); these counts are unvalidated and are for comparing models only."]
(pt.ROOT / "docs" / "paperA_checks.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L))
